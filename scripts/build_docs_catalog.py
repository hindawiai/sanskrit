#!/usr/bin/env python3
"""Mirror repository Markdown documentation into the GitHub Pages /docs tree."""
from pathlib import Path
import shutil, html

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
DEST = DOCS / "reference" / "repository"
GENERATED_PREFIX = Path("docs/reference/repository")

sources = []
for path in ROOT.rglob("*.md"):
    if any(part in {".git", "node_modules", "__pycache__"} for part in path.parts):
        continue
    rel = path.relative_to(ROOT)
    if rel == GENERATED_PREFIX or GENERATED_PREFIX in rel.parents:
        continue
    sources.append((rel, path))
sources.sort(key=lambda x: x[0].as_posix().lower())

if DEST.exists():
    shutil.rmtree(DEST)
items = []
for rel, path in sources:
    if rel.parts[:2] == ("docs", "reference"):
        # These curated mirrors already reside within the Pages root.
        href = rel.relative_to("docs").as_posix()
    else:
        target = DEST / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)
        href = f"reference/repository/{rel.as_posix()}"
    items.append(
        f'<li><a href="{html.escape(href, quote=True)}">{html.escape(rel.as_posix())}</a></li>'
    )

page = f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Complete Documentation Inventory · Pushkalāvatī</title><link rel="stylesheet" href="site.css"></head>
<body><header class="hero"><p class="eyebrow">DOCUMENTATION CATALOG</p>
<h1>Complete repository documentation</h1>
<p>Every Markdown document in the curated repository is available beneath this Pages site, preserving repository-relative paths where mirrored. These links serve the original Markdown text; interactive compiler tools are listed separately.</p>
<nav><a href="index.html">Lab home</a><a href="tasks.html">Tasks and features</a><a href="tests.html">Test register</a><a href="reference.html">Handoff viewer</a><a href="specifications/index.html">Language specifications</a></nav></header>
<main><section class="panel"><h2>All repository Markdown files ({len(sources)})</h2>
<p>Source documents are available at <code>docs/reference/repository/</code>; curated documents already published in <code>docs/reference/</code> are linked in place.</p>
<ul>{chr(10).join(items)}</ul></section></main><footer>Generated by scripts/build_docs_catalog.py · site root: docs/</footer></body></html>
'''
(DOCS / "documentation-catalog.html").write_text(page, encoding="utf-8")
print(f"Indexed {len(sources)} Markdown documents for GitHub Pages.")
