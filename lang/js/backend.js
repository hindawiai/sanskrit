#!/usr/bin/env node
"use strict";
const fs = require("node:fs");
const { parse, LITERALS } = require("./interpreter");

function safeName(name) {
  return `sutram_${name.replace(/[^A-Za-z0-9_]/g, ch => `_u${ch.codePointAt(0).toString(16)}_`)}`;
}
const cName = safeName, rustName = safeName;
function expr(expr, backend, fn) {
  if (expr.kind === "literal") return String(Number(expr.value));
  if (expr.kind === "name") {
    if (Object.prototype.hasOwnProperty.call(LITERALS, expr.value)) return String(Number(LITERALS[expr.value]));
    if (fn.params.includes(expr.value)) return `env_${safeName(expr.value)}`;
    throw new Error(`${fn.name}: unbound name ${expr.value}`);
  }
  throw new Error(`unsupported ${backend} expression kind ${expr.kind}`);
}
function validateBackend(program) {
  const emittedNames = new Map();
  for (const fn of Object.values(program.adhikaras)) {
    if (fn.params.length > 1) throw new Error(`${fn.name}: native backends support at most one parameter`);
    const emitted = safeName(fn.name);
    if (emittedNames.has(emitted)) throw new Error(`backend name collision: ${emittedNames.get(emitted)} and ${fn.name}`);
    emittedNames.set(emitted, fn.name);
    if (!fn.body.length || fn.body[0].op !== "karta") {
      throw new Error(`${fn.name}: native backend requires karta initialization as the first statement`);
    }
    const returns = fn.body.map((x, i) => x.op === "phala" ? i : -1).filter(i => i >= 0);
    if (returns.length !== 1 || returns[0] !== fn.body.length - 1) {
      throw new Error(`${fn.name}: exactly one terminal phala is required by native backends`);
    }
    for (const inst of fn.body) {
      if (inst.arg && typeof inst.arg === "object" && inst.arg.kind === "name" &&
          !Object.prototype.hasOwnProperty.call(LITERALS, inst.arg.value) &&
          !fn.params.includes(inst.arg.value)) {
        throw new Error(`${fn.name}:${inst.line}: unbound name ${inst.arg.value}`);
      }
      if (inst.op === "call") {
        const callee = program.adhikaras[inst.arg];
        if (!callee) throw new Error(`${fn.name}:${inst.line}: unknown adhikara ${inst.arg}`);
        if (callee.params.length > 1) throw new Error(`${fn.name}:${inst.line}: native backend supports unary calls only`);
      }
    }
  }
  const visiting = new Set(), visited = new Set();
  function visit(name) {
    if (visiting.has(name)) throw new Error(`recursive call cycle at ${name} is not supported by the native backend`);
    if (visited.has(name)) return;
    visiting.add(name);
    for (const inst of program.adhikaras[name].body) if (inst.op === "call") visit(inst.arg);
    visiting.delete(name); visited.add(name);
  }
  for (const name of Object.keys(program.adhikaras)) visit(name);
}
function lowerC(source, entry = null) {
  const program = typeof source === "string" ? parse(source) : source;
  validateBackend(program);
  const names = Object.keys(program.adhikaras), chosen = entry || names[names.length - 1];
  if (!program.adhikaras[chosen]) throw new Error(`unknown entry adhikara ${chosen}`);
  const out = [
    "/* Generated by the Sūtram C backend. Subset: integer state, arithmetic, unary calls, likh, phala. */",
    "#include <stdint.h>", "#include <stdio.h>", "#include <inttypes.h>", ""
  ];
  for (const name of names) out.push(`static int64_t ${cName(name)}(int64_t input);`);
  out.push("");
  for (const name of names) {
    const fn = program.adhikaras[name];
    out.push(`static int64_t ${cName(name)}(int64_t input) {`);
    if (fn.params.length) out.push(`  int64_t env_${safeName(fn.params[0])} = input;`, `  (void)env_${safeName(fn.params[0])};`);
    else out.push("  (void)input;");
    out.push(`  int64_t karta = ${expr(fn.body[0].arg, "C", fn)};`);
    for (const inst of fn.body.slice(1)) {
      switch (inst.op) {
        case "karta": out.push(`  karta = ${expr(inst.arg, "C", fn)};`); break;
        case "yoga": out.push(`  karta += ${expr(inst.arg, "C", fn)};`); break;
        case "viyoga": out.push(`  karta -= ${expr(inst.arg, "C", fn)};`); break;
        case "dviguna": out.push("  karta *= 2;"); break;
        case "likh": out.push('  printf("%" PRId64 "\\n", karta);'); break;
        case "phala": out.push("  return karta;"); break;
        case "call": out.push(`  karta = ${cName(inst.arg)}(karta);`); break;
        default: throw new Error(`unsupported operation ${inst.op}`);
      }
    }
    out.push("}", "");
  }
  out.push("int main(void) {", `  int64_t result = ${cName(chosen)}(0);`,
    `  fprintf(stderr, "{\\"entry\\":\\"${chosen}\\",\\"result\\":%" PRId64 "}\\n", result);`,
    "  return 0;", "}");
  return out.join("\n") + "\n";
}
function lowerRust(source, entry = null) {
  const program = typeof source === "string" ? parse(source) : source;
  validateBackend(program);
  const names = Object.keys(program.adhikaras), chosen = entry || names[names.length - 1];
  if (!program.adhikaras[chosen]) throw new Error(`unknown entry adhikara ${chosen}`);
  const out = ["// Generated by the Sūtram Rust backend.", ""];
  for (const name of names) {
    const fn = program.adhikaras[name];
    out.push(`fn ${rustName(name)}(input: i64) -> i64 {`);
    if (fn.params.length) out.push(`    let env_${safeName(fn.params[0])}: i64 = input;`, `    let _ = env_${safeName(fn.params[0])};`);
    else out.push("    let _ = input;");
    out.push(`    let mut karta: i64 = ${expr(fn.body[0].arg, "Rust", fn)};`);
    for (const inst of fn.body.slice(1)) {
      switch (inst.op) {
        case "karta": out.push(`    karta = ${expr(inst.arg, "Rust", fn)};`); break;
        case "yoga": out.push(`    karta += ${expr(inst.arg, "Rust", fn)};`); break;
        case "viyoga": out.push(`    karta -= ${expr(inst.arg, "Rust", fn)};`); break;
        case "dviguna": out.push("    karta *= 2;"); break;
        case "likh": out.push('    println!("{}", karta);'); break;
        case "phala": out.push("    return karta;"); break;
        case "call": out.push(`    karta = ${rustName(inst.arg)}(karta);`); break;
        default: throw new Error(`unsupported operation ${inst.op}`);
      }
    }
    out.push("}", "");
  }
  out.push("fn main() {", `    let result = ${rustName(chosen)}(0);`,
    `    eprintln!("entry=${chosen} result={}", result);`, "}");
  return out.join("\n") + "\n";
}
function main() {
  const [sourcePath, target = "c", entry] = process.argv.slice(2);
  if (!sourcePath || !["c", "rust"].includes(target)) {
    console.error("Usage: node lang/js/backend.js <program.su> <c|rust> [entry]");
    process.exit(2);
  }
  const source = fs.readFileSync(sourcePath, "utf8");
  process.stdout.write((target === "c" ? lowerC(source, entry) : lowerRust(source, entry)));
}
if (require.main === module) main();
module.exports = { lowerC, lowerRust, validateBackend };
